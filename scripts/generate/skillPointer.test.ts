import { describe, expect, test } from "bun:test";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import {
  BUNDLED_SKILL_NAMES,
  readBundledSkillDocument,
} from "../../packages/hunk/src/core/run/paths";
import { parseSkillFrontmatter, renderAgentSkillStub } from "./skillPointer";

const REVIEW_SKILL =
  "---\nname: hunk-review\ndescription: Drives a live Hunk session\n---\n\nFull instructions that must never be copied";

describe("skill pointers", () => {
  test("reads frontmatter with either line ending", () => {
    for (const document of [REVIEW_SKILL, REVIEW_SKILL.replaceAll("\n", "\r\n")]) {
      expect(parseSkillFrontmatter(document)).toEqual({
        name: "hunk-review",
        description: "Drives a live Hunk session",
      });
    }
  });

  test("rejects missing, incomplete, and unterminated frontmatter", () => {
    expect(() => parseSkillFrontmatter("# no frontmatter")).toThrow("missing its frontmatter");
    expect(() => parseSkillFrontmatter("---\nname: x\n---\n")).toThrow("must declare both");
    expect(() => parseSkillFrontmatter("---\nname: x\ndescription: y")).toThrow(
      "closing frontmatter",
    );
    expect(() => parseSkillFrontmatter("---\nname: x\n---\ndescription: body")).toThrow(
      "must declare both",
    );
  });

  test("renders discovery metadata and a command, not the full instructions", () => {
    const stub = renderAgentSkillStub(parseSkillFrontmatter(REVIEW_SKILL));

    expect(stub).toStartWith(
      "---\nname: hunk-review\ndescription: Drives a live Hunk session\n---",
    );
    expect(stub).toContain("<!-- generated by `bun run generate:skill` -->");
    expect(stub).toContain("hunk skill show hunk-review");
    expect(stub).toContain("hunk skill path hunk-review");
    expect(stub).not.toContain("Full instructions that must never be copied");
  });

  test("checked-in public pointers match bundled skill metadata", () => {
    const repoRoot = join(import.meta.dir, "..", "..");
    for (const name of BUNDLED_SKILL_NAMES) {
      const frontmatter = parseSkillFrontmatter(readBundledSkillDocument(name));
      expect(frontmatter.name).toBe(name);
      expect(frontmatter.description.length).toBeGreaterThan(20);

      const checkedIn = readFileSync(join(repoRoot, ".agents", "skills", name, "SKILL.md"), "utf8");
      expect(checkedIn.replaceAll("\r\n", "\n")).toBe(renderAgentSkillStub(frontmatter));
    }
  });

  test("maintainer skills are hidden from normal skills CLI discovery", () => {
    const repoRoot = join(import.meta.dir, "..", "..");
    for (const name of ["hunk-release", "hunk-launch-video"]) {
      const document = readFileSync(join(repoRoot, "skills", name, "SKILL.md"), "utf8");
      for (const text of [document, document.replaceAll("\r\n", "\n").replaceAll("\n", "\r\n")]) {
        expect(text.replaceAll("\r\n", "\n").split("---")[1]).toContain(
          "metadata:\n  internal: true",
        );
      }
    }
  });
});

/** Produce every committed generated documentation artifact. */
export function generateDocsArtifacts() {
  return {
    [GENERATED_DOC_PATHS.cli]: renderCliReference(),
    [GENERATED_DOC_PATHS.config]: renderConfigReference(),
    [GENERATED_DOC_PATHS.agentSkill]: renderHunkReviewSkill(),
  };
}

/** Write generated artifacts, or report stale paths without modifying them. */
export function updateGeneratedDocs({
  check = false,
  artifacts = generateDocsArtifacts(),
}: {
  check?: boolean;
  artifacts?: Readonly<Record<string, string>>;
} = {}) {
  const stalePaths: string[] = [];
  for (const [path, content] of Object.entries(artifacts)) {
    const current = (() => {
      try {
        return readFileSync(path, "utf8");
      } catch {
        return undefined;
      }
    })();
    if (current === content) {
      continue;
    }
    stalePaths.push(path);
    if (!check) {
      writeFileSync(path, content);
    }
  }
  return stalePaths;
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  const stalePaths = updateGeneratedDocs({ check });
  if (check && stalePaths.length > 0) {
    console.error("Generated documentation is stale:");
    for (const path of stalePaths) {
      console.error(`  ${path}`);
    }
    console.error("Run `bun run generate:docs` and commit the result.");
    process.exit(1);
  }
  if (!check) {
    console.log(
      stalePaths.length > 0
        ? `Updated ${stalePaths.length} generated documentation file(s).`
        : "Generated documentation is already current.",
    );
  }
}

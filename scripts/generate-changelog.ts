const REPO_URL = "https://github.com/modem-dev/hunk";
const SITE_ORIGIN = "https://hunk.dev";
const GENERATED_NOTICE =
  "<!-- GENERATED by `bun run generate:changelog`. Edit CHANGELOG.md or website/releases/notes.json instead. -->";

export const CHANGELOG_SOURCE = resolve(REPO_ROOT, "CHANGELOG.md");
export const RELEASE_NOTES_SOURCE = resolve(REPO_ROOT, "website", "releases", "notes.json");

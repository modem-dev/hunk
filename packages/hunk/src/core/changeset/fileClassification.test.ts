import { describe, expect, test } from "bun:test";
import {
  applyGeneratedPathDeclarations,
  classifyReviewNoise,
  reviewNoiseLabel,
} from "./fileClassification";
import type { DiffFile } from "./model";

/** Build a one-hunk added-file patch starting at the given new-file line. */
function createTestPatch(lines: string[], startLine = 1) {
  return [`@@ -0,0 +${startLine},${lines.length} @@`, ...lines.map((line) => `+${line}`)].join(
    "\n",
  );
}

/** Build the fields declaration handling reads from a diff file. */
function createTestDiffFile(path: string, reviewNoise?: DiffFile["reviewNoise"]) {
  return { id: path, path, reviewNoise } as DiffFile;
}

describe("classifyReviewNoise", () => {
  test("recognizes lockfiles by basename in any directory", () => {
    expect(classifyReviewNoise("bun.lock")).toBe("lockfile");
    expect(classifyReviewNoise("services/api/Cargo.lock")).toBe("lockfile");
  });

  test("recognizes minified assets and source maps", () => {
    expect(classifyReviewNoise("dist/app.min.js")).toBe("minified");
    expect(classifyReviewNoise("dist/app.css.map")).toBe("minified");
  });

  test("recognizes generated path shapes, including double extensions", () => {
    expect(classifyReviewNoise("api/service.pb.go")).toBe("generated");
    expect(classifyReviewNoise("src/schema.generated.ts")).toBe("generated");
    expect(classifyReviewNoise("src/schema.generated.d.ts")).toBe("generated");
  });

  test("recognizes generator headers in comments at the top of a file", () => {
    expect(classifyReviewNoise("a.ts", createTestPatch(["// @generated by tool"]))).toBe(
      "generated",
    );
    expect(
      classifyReviewNoise("a.go", createTestPatch(["// Code generated by x. DO NOT EDIT."])),
    ).toBe("generated");
  });

  test("ignores markers in prose, removed lines, and later hunks", () => {
    expect(classifyReviewNoise("a.md", createTestPatch(["The code is auto-generated."]))).toBe(
      undefined,
    );
    expect(classifyReviewNoise("a.ts", "@@ -1,1 +1,0 @@\n-// @generated")).toBe(undefined);
    expect(classifyReviewNoise("a.ts", createTestPatch(["// DO NOT EDIT"], 200))).toBe(undefined);
    expect(
      classifyReviewNoise(
        "a.ts",
        `${createTestPatch(["const a = 1;"])}\n${createTestPatch(["// DO NOT EDIT"], 200)}`,
      ),
    ).toBe(undefined);
  });

  test("leaves ordinary files unclassified", () => {
    expect(classifyReviewNoise("src/lockfile.ts", createTestPatch(["const a = 1;"]))).toBe(
      undefined,
    );
  });
});

describe("applyGeneratedPathDeclarations", () => {
  test("lets a repository declaration override the built-in rules both ways", () => {
    const files = [
      createTestDiffFile("src/client.ts"),
      createTestDiffFile("bun.lock", "lockfile"),
      createTestDiffFile("yarn.lock", "lockfile"),
    ];

    const result = applyGeneratedPathDeclarations(
      files,
      new Map([
        ["src/client.ts", true],
        ["bun.lock", false],
      ]),
    );

    expect(result.map((file) => file.reviewNoise)).toEqual(["generated", undefined, "lockfile"]);
  });
});

describe("reviewNoiseLabel", () => {
  test("falls back to a neutral label for manually collapsed files", () => {
    expect(reviewNoiseLabel("lockfile")).toBe("Lockfile");
    expect(reviewNoiseLabel(undefined)).toBe("File");
  });
});

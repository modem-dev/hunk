/**
 * Classifies diff files as generated review noise so the terminal review can collapse them.
 *
 * Built-in rules cover files that carry no repository declaration: lockfile names, minified
 * and generated path shapes, and generator headers at the top of a file. A repository's own
 * declaration, read by the VCS adapter, overrides them in both directions.
 */
import type { DiffFile, ReviewNoiseKind } from "./model";

const LOCKFILE_NAMES = new Set([
  "package-lock.json",
  "npm-shrinkwrap.json",
  "yarn.lock",
  "pnpm-lock.yaml",
  "bun.lock",
  "bun.lockb",
  "deno.lock",
  "cargo.lock",
  "composer.lock",
  "gemfile.lock",
  "poetry.lock",
  "pdm.lock",
  "pipfile.lock",
  "uv.lock",
  "go.sum",
  "packages.lock.json",
  "podfile.lock",
  "mix.lock",
  "flake.lock",
  "gradle.lockfile",
]);

const MINIFIED_PATH = /(\.min\.(js|mjs|cjs|css)|\.(js|mjs|cjs|css)\.map)$/i;

const GENERATED_PATHS = [
  /\.pb\.go$/i,
  /_pb2\.pyi?$/i,
  /\.pb\.(cc|h)$/i,
  /\.g\.dart$/i,
  /\.freezed\.dart$/i,
  /\.designer\.cs$/i,
  /\.generated\.[a-z.]+$/i,
];

// Requiring a comment shape keeps prose that merely mentions generated code out of the match.
const GENERATED_HEADER =
  /^\s*(\/\/|\/\*|\*|#|--|;|<!--).*(@generated|do not edit|code generated by|auto-?generated)/i;

const HUNK_HEADER = /^@@ -\d+(?:,\d+)? \+(\d+)/;

// Generator headers sit at the top of a file, so a later hunk's text is ordinary content.
const MAX_HEADER_START_LINE = 5;
const MAX_HEADER_SCAN_LINES = 40;

/** Report whether a patch adds or keeps a generator header at the top of the new file. */
function patchShowsGeneratedHeader(patch: string) {
  let scannedLines = 0;
  let lineStart = 0;
  let inTopHunk = false;

  while (lineStart < patch.length && scannedLines < MAX_HEADER_SCAN_LINES) {
    const newline = patch.indexOf("\n", lineStart);
    const lineEnd = newline < 0 ? patch.length : newline;
    const line = patch.slice(lineStart, lineEnd);
    lineStart = lineEnd + 1;

    const hunkHeader = HUNK_HEADER.exec(line);
    if (hunkHeader) {
      if (inTopHunk || Number(hunkHeader[1]) > MAX_HEADER_START_LINE) return false;
      inTopHunk = true;
      continue;
    }

    if (!inTopHunk) continue;

    scannedLines += 1;
    if ((line[0] === "+" || line[0] === " ") && GENERATED_HEADER.test(line.slice(1))) {
      return true;
    }
  }

  return false;
}

/** Classify one file from its path and patch, or return undefined for ordinary code. */
export function classifyReviewNoise(path: string, patch = ""): ReviewNoiseKind | undefined {
  const name = path.slice(path.lastIndexOf("/") + 1).toLowerCase();

  if (LOCKFILE_NAMES.has(name)) return "lockfile";
  if (MINIFIED_PATH.test(path)) return "minified";
  if (GENERATED_PATHS.some((pattern) => pattern.test(path))) return "generated";
  return patchShowsGeneratedHeader(patch) ? "generated" : undefined;
}

/** Name one noise kind for the row that stands in for a collapsed file. */
export function reviewNoiseLabel(kind: ReviewNoiseKind | undefined) {
  switch (kind) {
    case "lockfile":
      return "Lockfile";
    case "minified":
      return "Minified file";
    case "generated":
      return "Generated file";
    default:
      return "File";
  }
}

/** Apply a repository's generated-path declarations, leaving undeclared files as classified. */
export function applyGeneratedPathDeclarations(
  files: DiffFile[],
  declarations: ReadonlyMap<string, boolean>,
): DiffFile[] {
  return files.map((file) => {
    const declared = declarations.get(file.path);
    if (declared === undefined) return file;

    const { reviewNoise: _reviewNoise, ...undeclared } = file;
    return declared ? { ...undeclared, reviewNoise: "generated" as const } : undeclared;
  });
}

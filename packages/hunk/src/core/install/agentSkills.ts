import fs from "node:fs";
import { homedir } from "node:os";
import { dirname, join, relative, sep } from "node:path";
import { HunkUserError } from "../run/errors";
import {
  type BundledSkillName,
  readBundledSkillDocument,
  resolveUserConfigDir,
} from "../run/paths";

/**
 * Runs `hunk skill install`: writes a thin pointer skill into a coding agent's skill directory.
 *
 * The installed file is deliberately not a copy of the bundled skill. It carries only the
 * frontmatter an agent needs to decide when to load it (`name` and `description`, read from the
 * bundled document at install time) and a body that tells the agent to run `hunk skill show` for
 * the real instructions. The installed Hunk binary therefore stays the single owner of the skill
 * text, and upgrading Hunk never leaves a stale copy behind in an agent's directory.
 *
 * Every agent host is one row in `AGENT_SKILL_HOSTS`: where it reads user-wide skills and where
 * it reads repository skills. Filesystem access, the environment, the home directory, and the
 * bundled skill text all arrive through `AgentSkillInstallIo` so tests run against a scratch tree.
 */

/** Marker every generated pointer skill carries so reinstalls can tell their own files apart. */
export const AGENT_SKILL_STUB_MARKER = "<!-- generated by `hunk skill install` -->";

/**
 * Report whether a SKILL.md has the exact shape `renderAgentSkillStub` writes: a frontmatter block,
 * one blank line, then the marker. A hand-written skill that merely quotes the marker somewhere in
 * its body is not Hunk's to overwrite, so the position matters, not just the presence.
 */
export function isHunkGeneratedSkill(document: string) {
  const lines = document.replaceAll("\r\n", "\n").split("\n");
  if (lines[0] !== "---") {
    return false;
  }
  const closing = lines.indexOf("---", 1);
  return (
    closing !== -1 && lines[closing + 1] === "" && lines[closing + 2] === AGENT_SKILL_STUB_MARKER
  );
}

/** Inputs a host needs to resolve its user-wide skills directory. */
interface AgentSkillHostContext {
  env: NodeJS.ProcessEnv;
  home: string;
}

/** One coding agent Hunk can install a pointer skill for. */
export interface AgentSkillHost {
  /** Value accepted by `--agent`. */
  readonly id: string;
  /** Product name shown in output and docs. */
  readonly label: string;
  /** Other spellings `--agent` accepts for this host. */
  readonly aliases?: readonly string[];
  /** Directory holding `<skill>/SKILL.md` for every project on this machine. */
  readonly userSkillsDir: (context: AgentSkillHostContext) => string;
  /** Directory, relative to a repository root, holding that repository's skills. */
  readonly projectSkillsDir: string;
}

/** Resolve `$XDG_CONFIG_HOME`-style config roots the way Hunk resolves its own. */
function configDir(context: AgentSkillHostContext) {
  return resolveUserConfigDir(context.env) ?? join(context.home, ".config");
}

